/**
 * Prepares this checkout for GitHub Pages and writes a static export to `out/`.
 *
 * GitHub Pages serves files only, so the server runtime has to go before
 * `output: "export"` can build: the API route handlers, the referral proxy and
 * the searchParams/session pages are moved aside into `.pages-server/` and the
 * `force-dynamic` flags are stripped so the remaining pages prerender against
 * their existing static fallbacks.
 *
 * This mutates the checkout, so it refuses to run unless git reports a clean
 * tree — meant for a CI checkout (or a throwaway clone), never a working copy.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const base = process.env.PAGES_BASE ?? `/${join(root, "..").split(/[\\/]/).pop()}`;
if (!/^\/[A-Za-z0-9._~-]*$/.test(base)) {
  throw new Error(`PAGES_BASE must be a single path segment starting with "/", got ${JSON.stringify(base)}`);
}

requireCleanCheckout();

const stash = join(root, ".pages-server");
rmSync(stash, { recursive: true, force: true });
mkdirSync(stash, { recursive: true });

// Absent from the export: unsupported by `output: "export"`, or pointless
// without a server. Stashed rather than deleted so the checkout stays restorable.
for (const path of ["src/app/api", "src/proxy.ts", "src/app/admin", "src/app/dashboard"]) {
  const from = join(root, path);
  if (!existsSync(from)) continue;
  renameSync(from, join(stash, path.replaceAll(/[\\/]/g, "__")));
  console.log(`  stashed ${path}`);
}

let stripped = 0;
for (const file of findFiles(join(root, "src"), ".tsx")) {
  const source = readFileSync(file, "utf8");
  const cleaned = source.replace(/^export const dynamic\s*=\s*"force-dynamic";\r?\n/gm, "");
  if (cleaned !== source) {
    writeFileSync(file, cleaned);
    stripped++;
  }
}

writeFileSync(
  join(root, "next.config.ts"),
  `import type { NextConfig } from "next";

// Generated by scripts/pages-build.mjs for the GitHub Pages static export.
const nextConfig: NextConfig = {
  output: "export",
  basePath: ${JSON.stringify(base)},
  assetPrefix: ${JSON.stringify(`${base}/`)},
  trailingSlash: true,
  images: { unoptimized: true },
  turbopack: { root: process.cwd() },
};

export default nextConfig;
`
);

console.log(`static export: basePath=${base}  stripped force-dynamic from ${stripped} pages`);

execFileSync(process.execPath, [join(root, "node_modules", "next", "dist", "bin", "next"), "build"], {
  cwd: root,
  stdio: "inherit",
  env: { ...process.env, NEXT_TELEMETRY_DISABLED: "1" },
});

function requireCleanCheckout() {
  const dirty = execFileSync("git", ["status", "--porcelain"], { cwd: root, encoding: "utf8" }).trim();
  if (dirty) {
    throw new Error(
      "refusing to mutate a working copy with uncommitted changes — run this in CI or a throwaway clone"
    );
  }
}

function findFiles(dir, extension) {
  const found = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) found.push(...findFiles(path, extension));
    else if (entry.name.endsWith(extension)) found.push(path);
  }
  return found;
}
